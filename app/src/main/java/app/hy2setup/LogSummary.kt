/** Простая расшифровка журнала: итог одной фразой и пояснения обычными словами. */
data class LogSummary(val state: State, val headline: String, val points: List<String>) {

    enum class State { OK, WARN, ERROR, RUNNING, INFO }

    /** Ключевое событие журнала для краткого вида: шаг, успех, предупреждение, ошибка. */
    data class Event(val state: State, val text: String)

    companion object {
        /**
         * Краткий журнал: только заголовки шагов (▶), итоги (✓/✗), предупреждения и ошибки — без технического вывода.
         * Последний шаг без итога, пока идёт работа, — «выполняется».
         */
        fun events(log: List<String>, running: Boolean, max: Int = 8): List<Event> {
            val out = mutableListOf<Event>()
            for (raw in log) {
                val l = raw.trim()
                val e = when {
                    l.startsWith("▶ ") -> Event(State.RUNNING, l.removePrefix("▶ "))
                    l.startsWith("✓") -> Event(State.OK, l.removePrefix("✓").trim())
                    l.startsWith("✗") || l.startsWith("ОШИБКА") || l.startsWith("ПРОБЛЕМА") -> Event(State.ERROR, l.removePrefix("✗").trim())
                    l.startsWith("ПРЕДУПРЕЖДЕНИЕ") || l.startsWith("! ") || l.startsWith("• ") -> Event(State.WARN, l.removePrefix("• ").removePrefix("! ").trim())
                    l.startsWith("Готово") -> Event(State.OK, l)
                    else -> null
                } ?: continue
                // шаг, после которого что-то случилось, уже не «выполняется»: ошибка — его, иначе он пройден
                if (out.isNotEmpty() && out.last().state == State.RUNNING) {
                    out[out.size - 1] = out.last().copy(state = if (e.state == State.ERROR) State.ERROR else State.OK)
                }
                out += e
            }
            if (!running && out.isNotEmpty() && out.last().state == State.RUNNING) out[out.size - 1] = out.last().copy(state = State.INFO)
            return out.takeLast(max)
        }

