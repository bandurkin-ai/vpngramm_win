        private val STEP = Regex("^(==>|▶)\\s*(.+)$")

        fun of(lines: List<String>, running: Boolean): LogSummary {
            if (lines.isEmpty()) return LogSummary(State.INFO, "Журнал пуст", emptyList())
            val stage = lines.lastOrNull { STEP.matches(it.trim()) }
                ?.let { STEP.find(it.trim())!!.groupValues[2] }
            val points = LinkedHashSet<String>()
            for (raw in lines) {
                val line = raw.trim()
                HINTS.firstOrNull { it.first.containsMatchIn(line) }?.let { points += it.second }
            }
            val securityFailed = lines.any { "ОШИБКА БЕЗОПАСНОСТИ" in it }
            val hasError = lines.any { val t = it.trim(); t.startsWith("ОШИБКА") && "БЕЗОПАСНОСТИ" !in t } ||
                lines.any { Regex("завершилась с ошибкой|Завершено с кодом [1-9]").containsMatchIn(it) }
            val done = lines.any { "Готово!" in it || it.startsWith("Ссылок получено") }
            val hasWarn = lines.any { "ПРЕДУПРЕЖДЕНИЕ" in it || it.startsWith("ПРОБЛЕМА:") } || securityFailed
            val secured = lines.any { "Сервер защищён" in it || "Вход по паролю отключён" in it }
            val live = lines.any { it.startsWith("Живая проверка завершена") }
            val check = lines.lastOrNull { it.startsWith("Проверка завершена:") }
                ?: if (live) {
                    val n = lines.count { it.startsWith("ПРОБЛЕМА:") }
                    if (n == 0) "Проверка завершена: проблем не найдено." else "Проверка завершена: найдено проблем — $n."
                } else null
            val checkFailed = check != null && "найдено проблем" in check

            if (running) {
                return LogSummary(State.RUNNING, "Выполняется" + (stage?.let { ": $it" } ?: "…"), points.toList())
            }
            if (hasError && !done) {
                if (points.isEmpty()) points += "Подробности — в последних строках журнала. Его можно скопировать кнопкой ниже."
                return LogSummary(
                    State.ERROR,
                    "Не получилось" + (stage?.let { " на этапе «$it»" } ?: ""),
                    points.toList(),
                )
            }
            if (done) {
                val head = when {
                    checkFailed -> "Сервер настроен, но проверка нашла проблемы — см. ниже"
                    securityFailed -> "Протокол работает, но защита не включилась"
                    secured -> "Готово: протокол работает, сервер защищён"
                    else -> "Готово: всё прошло успешно"
                }
                return LogSummary(if (hasWarn) State.WARN else State.OK, head, points.toList())
            }
            if (check != null) {
                return LogSummary(
                    if (checkFailed) State.WARN else State.OK,
                    if (checkFailed) check.removePrefix("Проверка завершена: ").replaceFirstChar { it.uppercase() } else "Проверка: проблем не найдено",
                    points.toList(),
                )
            }
            return LogSummary(if (hasWarn) State.WARN else State.INFO, "Завершено", points.toList())
        }
    }
